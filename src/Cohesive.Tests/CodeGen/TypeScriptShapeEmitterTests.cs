    [Fact]
    public void Emit_PresentationModule_IncludesExpressionAndTypeReferenceUnions()
    {
        var graph = new ClrShapeGraphBuilder()
            .AddShape(typeof(PresentationModuleDefinition))
            .Build();

        var expr = Assert.IsType<TypeDefinition.Union>(
            Assert.Single(graph.NamedTypes, type => type.Name == nameof(Expr)));
        Assert.Equal("$expr", expr.Discriminator.FieldName);
        Assert.Contains(expr.Cases, @case => @case.DiscriminatorValue == "parameter");

        var typeRef = Assert.IsType<TypeDefinition.Union>(
            Assert.Single(graph.NamedTypes, type => type.Name == nameof(TypeRef)));
        Assert.Equal("$type", typeRef.Discriminator.FieldName);
        Assert.Contains(typeRef.Cases, @case => @case.DiscriminatorValue == "scalar");

        var emission = new TypeScriptShapeEmitter(new TypeScriptEmitterOptions
        {
            EmitAutoGeneratedHeader = false,
