        Assert.Contains("Status: LabeledShipmentStatus;", text, StringComparison.Ordinal);
    }

    [Fact]
    public void Emit_IrFirstGraph_UsesNamedTypesWithoutClrReflection()
    {
        var statusType = new TypeDefinition.Enum(
            id: new TypeId("type:orderStatus"),
            underlying: PrimitiveType.String,
            values:
            [
                new EnumValue("Pending"),
                new EnumValue("Completed")
            ]);

        var addressType = new TypeDefinition.Structural(
            id: new TypeId("type:address"),
            fields:
            [
                new StructuralField(new FieldName("Street"), new ScalarTypeRef(ScalarTypeKind.String)),
                new StructuralField(
                    new FieldName("PostalCode"),
                    new ScalarTypeRef(ScalarTypeKind.String),
                    presence: FieldPresence.Optional,
                    nullability: FieldNullability.Nullable)
            ]);

        var orderShape = new Shape(
            id: new ShapeId("shape:order"),
            role: ShapeRoles.Entity,
            fields:
            [
                new FieldDefinition(
                    name: new FieldName("Id"),
                    type: new ScalarTypeRef(ScalarTypeKind.String)),
                new FieldDefinition(
                    name: new FieldName("Status"),
                    type: new NamedTypeRef(statusType.Id)),
                new FieldDefinition(
                    name: new FieldName("ShipTo"),
                    type: new NamedTypeRef(addressType.Id))
            ]);

        var request = ShapeCodeGenerationRequest.FromShape(orderShape, [statusType, addressType]);
        var emission = new TypeScriptShapeEmitter(new TypeScriptEmitterOptions
        {
            EmitAutoGeneratedHeader = false,
            NewLine = "\n"
        }).Emit(request);

        var text = Assert.Single(emission.Documents).Text;
        Assert.Contains("export type OrderStatus = 'Pending' | 'Completed';", text, StringComparison.Ordinal);
        Assert.Contains("export const orderStatuses = {\n  pending: 'Pending',\n  completed: 'Completed',\n} as const satisfies Record<string, OrderStatus>;", text, StringComparison.Ordinal);
        Assert.Contains("export const orderStatusLabels: Record<OrderStatus, string> = {\n  Pending: 'Pending',\n  Completed: 'Completed',\n};", text, StringComparison.Ordinal);
        Assert.Contains("export interface Address", text, StringComparison.Ordinal);
        Assert.Contains("PostalCode?: string | null;", text, StringComparison.Ordinal);
        Assert.Contains("export interface Order", text, StringComparison.Ordinal);
        Assert.Contains("ShipTo: Address;", text, StringComparison.Ordinal);
    }

    [Fact]
    public void Emit_UndefinedNumericEnumField_PreservesCardinalityAndNullability()
    {
        var statusType = new TypeDefinition.Enum(
