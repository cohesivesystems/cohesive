    }

    [Fact]
    public void Emit_ExternalTypeModules_ImportsAndReexportsExternalShapeTypes()
    {
        var graph = new ClrShapeGraphBuilder()
            .AddShape<PresentationEnvelope>()
            .Build();

        var emission = new TypeScriptShapeEmitter(new TypeScriptEmitterOptions
        {
            EmitAutoGeneratedHeader = false,
            ExternalTypeModules =
            [
                new TypeScriptExternalTypeModule
                {
                    TypeIdPrefix = "clr:type:Cohesive.Presentation.",
                    ShapeIdPrefix = "clr:shape:Cohesive.Presentation.",
                    ImportPath = "./cohesive.shapes.generated"
                },
                new TypeScriptExternalTypeModule
                {
                    TypeIdPrefix = "clr:type:Cohesive.Model.",
                    ShapeIdPrefix = "clr:shape:Cohesive.Model.",
                    ImportPath = "./cohesive.shapes.generated"
                }
            ],
            NewLine = "\n"
        }).Emit(new ShapeCodeGenerationRequest(graph));

        var text = Assert.Single(emission.Documents).Text;
        Assert.Contains("import type {", text, StringComparison.Ordinal);
        Assert.Contains("PresentationModuleDefinition", text, StringComparison.Ordinal);
        Assert.Contains("} from './cohesive.shapes.generated';", text, StringComparison.Ordinal);
        Assert.Contains("export type {", text, StringComparison.Ordinal);
        Assert.DoesNotContain("export interface PresentationModuleDefinition", text, StringComparison.Ordinal);
        Assert.Contains("export interface PresentationEnvelope", text, StringComparison.Ordinal);
        Assert.Contains("Module: PresentationModuleDefinition;", text, StringComparison.Ordinal);
    }

    static int CountOccurrences(string text, string value)
    {
        var count = 0;
        var index = 0;
        while ((index = text.IndexOf(value, index, StringComparison.Ordinal)) >= 0)
        {
            count++;
            index += value.Length;
        }

        return count;
    }

    sealed record ShipmentDto(
        string Id,
        ShipmentStatus Status,
        Distance Distance,
        IReadOnlyList<RouteStopDto> Stops,
        string? Notes,
        DateTimeOffset UpdatedAt);

    sealed record PresentationEnvelope(string Id, PresentationModuleDefinition Module);

    sealed record RouteStopDto(string Code, decimal? DelayHours);

    enum ShipmentStatus
    {
        Pending = 0,
        Confirmed = 1
    }
}

sealed record LabeledShipmentDto(LabeledShipmentStatus Status);

public enum LabeledShipmentStatus
{
    [CodeSet("Awaiting pickup", Description = "Waiting for dock assignment.")]
    AwaitingPickup = 0,

    [Code("loaded", Label = "Loaded on trailer", Description = "Freight has left the dock.")]
    Loaded = 1
}
