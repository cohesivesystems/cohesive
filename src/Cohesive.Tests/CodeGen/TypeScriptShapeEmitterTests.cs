    [Fact]
    public void Emit_PocoGraph_GeneratesTypeScriptForReactFriendlyDtos()
    {
        var graph = new ClrShapeGraphBuilder()
            .AddShape<ShipmentDto>(ShapeRoles.Entity)
            .Build();

        Assert.Single(graph.Shapes);
        Assert.Contains(graph.NamedTypes, x => x.Id.Value.EndsWith(nameof(RouteStopDto), StringComparison.Ordinal));
        Assert.Contains(graph.NamedTypes, x => x.Id.Value.EndsWith(nameof(ShipmentStatus), StringComparison.Ordinal));

        var emitter = new TypeScriptShapeEmitter(new TypeScriptEmitterOptions
        {
            FileName = "shipment.generated.ts",
            NewLine = "\n",
            EmitAutoGeneratedHeader = true
        });

        var emission = emitter.Emit(new ShapeCodeGenerationRequest(graph));
        var document = Assert.Single(emission.Documents);

        Assert.Equal("typescript", emission.Language);
        Assert.Equal("shipment.generated.ts", document.FileName);
        Assert.Contains("/* <auto-generated/> */", document.Text, StringComparison.Ordinal);
        Assert.Contains("export type ShipmentStatus = 0 | 1;", document.Text, StringComparison.Ordinal);
        Assert.Contains("export const shipmentStatuses = {\n  pending: 0,\n  confirmed: 1,\n} as const satisfies Record<string, ShipmentStatus>;", document.Text, StringComparison.Ordinal);
        Assert.Contains("export const shipmentStatusLabels: Record<ShipmentStatus, string> = {\n  0: 'Pending',\n  1: 'Confirmed',\n};", document.Text, StringComparison.Ordinal);
        Assert.Contains("export interface RouteStopDto", document.Text, StringComparison.Ordinal);
        Assert.Contains("DelayHours?: number | null;", document.Text, StringComparison.Ordinal);
        Assert.Contains("export interface ShipmentDto", document.Text, StringComparison.Ordinal);
        Assert.Contains("Status: ShipmentStatus;", document.Text, StringComparison.Ordinal);
        Assert.Contains("Distance: number;", document.Text, StringComparison.Ordinal);
        Assert.Contains("Stops: RouteStopDto[];", document.Text, StringComparison.Ordinal);
        Assert.Contains("Notes?: string | null;", document.Text, StringComparison.Ordinal);
        Assert.Equal(1, CountOccurrences(document.Text, "export interface ShipmentDto"));
    }

    [Fact]
