    static int DefaultMockStatusCode(ApiResultKind kind, Type bodyType) =>
        kind switch
        {
            ApiResultKind.Success when bodyType == typeof(void) => 204,
            ApiResultKind.Success => 200,
            ApiResultKind.Created => 201,
            ApiResultKind.Accepted => 202,
            ApiResultKind.NoContent => 204,
            ApiResultKind.ValidationFailed => 400,
            ApiResultKind.Unauthorized => 401,
            ApiResultKind.Forbidden => 403,
            ApiResultKind.NotFound => 404,
            ApiResultKind.Conflict => 409,
            ApiResultKind.PreconditionFailed => 412,
            ApiResultKind.RateLimited => 429,
            ApiResultKind.DomainError => 422,
            ApiResultKind.InfrastructureError => 500,
            _ => bodyType == typeof(void) ? 204 : 200
        };

    static ImmutableArray<QueryPropertyModel> BuildQueryProperties(HttpBinding http)
    {
        var properties = ImmutableArray.CreateBuilder<QueryPropertyModel>();
        if (http.Query is { } query)
        {
            var queryTypeText = GetTypeScriptTypeText(query.QueryType);
            var metadata = ShapeTypeInspector.GetReadablePropertyMetadata(query.QueryType);
            for (var i = 0; i < metadata.Length; i++)
            {
                var property = metadata[i].Property;
                properties.Add(new QueryPropertyModel(
                    PropertyName: property.Name,
                    QueryName: ResolveQueryParameterName(property),
                    TypeText: $"{queryTypeText}['{property.Name}']",
                    Decoder: GetQueryDecoderName(property.PropertyType),
                    IsArray: IsSequenceType(property.PropertyType)));
            }
        }

        for (var i = 0; i < http.Parameters.Count; i++)
        {
            var parameter = http.Parameters[i];
            if (parameter.Source != HttpParameterSource.Query)
                continue;

            properties.Add(new QueryPropertyModel(
                PropertyName: ToCamelCase(parameter.Name),
                QueryName: parameter.Name,
                TypeText: GetTypeScriptTypeText(parameter.Type),
                Decoder: GetQueryDecoderName(parameter.Type),
                IsArray: IsSequenceType(parameter.Type)));
        }

        return properties.ToImmutable();
    }

    static ImmutableArray<string> CollectTypeImports(IReadOnlyList<OperationModel> models)
    {
        var names = new List<string>();
        for (var i = 0; i < models.Count; i++)
        {
            var operation = models[i].Operation;
            var http = models[i].Http;
            AppendTypeImports(names, http.Body?.BodyType);
            AppendTypeImports(names, http.Query?.QueryType);

            for (var parameterIndex = 0; parameterIndex < http.Parameters.Count; parameterIndex++)
                AppendTypeImports(names, http.Parameters[parameterIndex].Type);

            for (var resultIndex = 0; resultIndex < operation.Results.Count; resultIndex++)
                AppendTypeImports(names, operation.Results[resultIndex].BodyType);
        }

        names.Sort(StringComparer.Ordinal);
        return [.. names];
    }

    static void AppendTypeImports(List<string> names, Type? type)
    {
        if (type is null)
            return;

        var elementType = UnwrapType(type);
        if (IsBuiltInType(elementType))
            return;

        var name = GetTypeName(elementType);
        if (!names.Contains(name, StringComparer.Ordinal))
            names.Add(name);
    }

    static string GetTypeScriptTypeText(Type type)
    {
        if (type == typeof(void))
            return "void";

        var nullable = Nullable.GetUnderlyingType(type);
        if (nullable is not null)
            return $"{GetTypeScriptTypeText(nullable)} | null";

        if (type == typeof(string) || type == typeof(Guid) || type == typeof(DateOnly) || type == typeof(TimeOnly)
            || type == typeof(DateTime) || type == typeof(DateTimeOffset) || type == typeof(char))
        {
            return "string";
        }

        if (type == typeof(bool))
            return "boolean";

        if (IsNumeric(type))
            return "number";

        if (type.IsEnum)
            return GetTypeName(type);

        if (type.IsArray)
            return $"{GetTypeScriptTypeText(type.GetElementType()!)}[]";

        if (TryGetSequenceElementType(type, out var elementType))
            return $"{GetTypeScriptTypeText(elementType!)}[]";

        return GetTypeName(type);
    }

    static string GetQueryDecoderName(Type type)
    {
        var unwrapped = UnwrapType(type);
        if (IsSequenceType(unwrapped) && TryGetSequenceElementType(unwrapped, out var elementType))
            unwrapped = UnwrapType(elementType!);

        if (unwrapped == typeof(bool))
            return "readApiMockBoolean";

        if (IsNumeric(unwrapped) || unwrapped.IsEnum)
            return "readApiMockNumber";

        return "readApiMockString";
    }

    static string GetArrayDecoderExpression(QueryPropertyModel property) =>
        property.Decoder switch
        {
            "readApiMockBoolean" => "(value) => readApiMockBoolean(value) ?? false",
            "readApiMockNumber" => "(value) => readApiMockNumber(value) ?? 0",
            _ => "(value) => readApiMockString(value) ?? ''"
        };

    static Type UnwrapType(Type type)
    {
        var nullable = Nullable.GetUnderlyingType(type);
        if (nullable is not null)
            return UnwrapType(nullable);

        if (type.IsArray)
            return UnwrapType(type.GetElementType()!);

        if (TryGetSequenceElementType(type, out var elementType))
            return UnwrapType(elementType!);

        return type;
    }

    static bool IsBuiltInType(Type type)
    {
        if (type == typeof(void)
            || type == typeof(string)
            || type == typeof(Guid)
            || type == typeof(DateOnly)
            || type == typeof(TimeOnly)
            || type == typeof(DateTime)
            || type == typeof(DateTimeOffset)
            || type == typeof(char)
            || type == typeof(bool))
        {
            return true;
        }

        return IsNumeric(type);
    }

    static bool IsNumeric(Type type) =>
        type == typeof(byte)
        || type == typeof(sbyte)
        || type == typeof(short)
        || type == typeof(ushort)
        || type == typeof(int)
        || type == typeof(uint)
        || type == typeof(long)
        || type == typeof(ulong)
        || type == typeof(float)
        || type == typeof(double)
        || type == typeof(decimal);

    static bool IsSequenceType(Type type) =>
        type != typeof(string) && TryGetSequenceElementType(type, out _);

    static bool TryGetSequenceElementType(Type type, out Type? elementType)
    {
        if (type == typeof(string))
        {
            elementType = null;
            return false;
        }

        if (type.IsArray)
        {
            elementType = type.GetElementType();
            return elementType is not null;
        }

        var interfaces = type.GetInterfaces();
        for (var i = 0; i < interfaces.Length; i++)
        {
            var candidate = interfaces[i];
            if (!candidate.IsGenericType || candidate.GetGenericTypeDefinition() != typeof(IEnumerable<>))
                continue;

            elementType = candidate.GetGenericArguments()[0];
            return true;
        }

        elementType = null;
        return false;
    }

    static bool CanSkipWhenUndefined(Type type) =>
        Nullable.GetUnderlyingType(type) is not null || !type.IsValueType;

    static string ResolveQueryParameterName(PropertyInfo property) =>
        property.GetCustomAttribute<JsonPropertyNameAttribute>(inherit: true)?.Name ?? ToSnakeCase(property.Name);

    static int CountRouteParameters(string route)
    {
        var count = 0;
        for (var i = 0; i < route.Length; i++)
        {
            if (route[i] == '{')
                count++;
        }

        return count;
    }

    static int CountRouteSegments(string route) =>
        route.Split('/', StringSplitOptions.RemoveEmptyEntries).Length;

    static string StripEntitySuffix(string value)
    {
        foreach (var suffix in new[] { "Resource", "Dto", "Entity", "Record" })
        {
            if (value.EndsWith(suffix, StringComparison.Ordinal) && value.Length > suffix.Length)
                return value[..^suffix.Length];
        }

        return value;
    }

    static string Pluralize(string value)
    {
        if (value.EndsWith("y", StringComparison.OrdinalIgnoreCase) && value.Length > 1 && !IsVowel(value[^2]))
            return $"{value[..^1]}ies";
        if (value.EndsWith("s", StringComparison.OrdinalIgnoreCase)
            || value.EndsWith("x", StringComparison.OrdinalIgnoreCase)
            || value.EndsWith("z", StringComparison.OrdinalIgnoreCase)
            || value.EndsWith("ch", StringComparison.OrdinalIgnoreCase)
            || value.EndsWith("sh", StringComparison.OrdinalIgnoreCase))
        {
            return $"{value}es";
        }

        return $"{value}s";
    }

    static bool IsVowel(char value) => char.ToLowerInvariant(value) is 'a' or 'e' or 'i' or 'o' or 'u';

    static string ToSnakeCase(string value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return value;

        var builder = new StringBuilder(value.Length + 8);
        for (var i = 0; i < value.Length; i++)
        {
            var current = value[i];
            if (char.IsUpper(current))
            {
                if (i > 0 && (char.IsLower(value[i - 1]) || char.IsDigit(value[i - 1])
                              || (i + 1 < value.Length && char.IsLower(value[i + 1]))))
                {
                    builder.Append('_');
                }

                builder.Append(char.ToLowerInvariant(current));
                continue;
            }

            builder.Append(current);
        }

        return builder.ToString();
    }

    static string ToPascalCase(string value) => SanitizeIdentifier(value, pascalCase: true);

    static string ToCamelCase(string value)
    {
        var pascal = SanitizeIdentifier(value, pascalCase: true);
        return pascal.Length == 1
            ? char.ToLowerInvariant(pascal[0]).ToString()
            : char.ToLowerInvariant(pascal[0]) + pascal[1..];
    }

    static string SanitizeIdentifier(string value, bool pascalCase)
    {
        if (string.IsNullOrWhiteSpace(value))
            return pascalCase ? "Value" : "value";

        var builder = new StringBuilder(value.Length);
        var upperNext = pascalCase;
        for (var i = 0; i < value.Length; i++)
        {
            var current = value[i];
            if (!char.IsLetterOrDigit(current))
            {
                upperNext = true;
                continue;
            }

            if (builder.Length == 0 && char.IsDigit(current))
                builder.Append('_');

            builder.Append(upperNext ? char.ToUpperInvariant(current) : current);
            upperNext = false;
        }

        if (builder.Length == 0)
            return pascalCase ? "Value" : "value";

        return builder.ToString();
    }

    static string GetTypeName(Type type)
    {
        var name = type.Name;
        var genericTick = name.IndexOf('`');
        return genericTick >= 0 ? name[..genericTick] : name;
    }

    static string Quote(string value)
    {
        var builder = new StringBuilder(value.Length + 2);
        builder.Append('\'');
        for (var i = 0; i < value.Length; i++)
        {
            var current = value[i];
            switch (current)
            {
                case '\'':
                    builder.Append("\\'");
                    break;
                case '\\':
                    builder.Append("\\\\");
                    break;
                case '\n':
                    builder.Append("\\n");
                    break;
                case '\r':
                    builder.Append("\\r");
                    break;
                case '\t':
                    builder.Append("\\t");
                    break;
                default:
                    builder.Append(current);
                    break;
            }
        }

        builder.Append('\'');
        return builder.ToString();
    }

    static int EstimateInitialCapacity(ApiDefinition definition) =>
        4096 + (definition.Operations.Count * 900);

