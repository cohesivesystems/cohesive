    static void WriteResultBuilders(ref PooledCodeWriter writer, string modulePrefix, IReadOnlyList<OperationModel> models)
    {
        var camelPrefix = ToCamelCase(modulePrefix);
        writer.Write("const ");
        writer.Write(camelPrefix);
        writer.WriteLine("ApiResultBuilders = {");
        writer.PushIndent();
        for (var i = 0; i < models.Count; i++)
        {
            var model = models[i];
            writer.Write(model.Key);
            writer.WriteLine(": {");
            writer.PushIndent();
            for (var resultIndex = 0; resultIndex < model.Results.Length; resultIndex++)
                WriteResultBuilderMethod(ref writer, camelPrefix, model, model.Results[resultIndex]);

            writer.PopIndent();
            writer.WriteLine("},");
        }

        writer.PopIndent();
        writer.Write("} as const satisfies ");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiResultBuilderByEndpoint;");
        writer.WriteLine();
    }

    static void WriteResultBuilderMethod(
        ref PooledCodeWriter writer,
        string camelPrefix,
        OperationModel model,
        ResultModel result)
    {
        writer.Write(result.MethodName);
        if (result.IsVoid)
        {
            writer.Write(": () => semanticNoContent(");
            writer.Write(camelPrefix);
            writer.Write("ApiResults.");
            writer.Write(model.Key);
            writer.Write(".");
            writer.Write(result.MethodName);
            writer.WriteLine("),");
            return;
        }

        writer.Write(": (body: ");
        writer.Write(result.BodyTypeText);
        writer.Write(") => semanticResult(");
        writer.Write(camelPrefix);
        writer.Write("ApiResults.");
        writer.Write(model.Key);
        writer.Write(".");
        writer.Write(result.MethodName);
        writer.WriteLine(", body),");
    }

    void WriteInstallFunction(ref PooledCodeWriter writer, string modulePrefix)
    {
        writer.Write("export async function install");
        writer.Write(modulePrefix);
        writer.Write("ApiMock(page: Page, handlers: ");
        writer.Write(modulePrefix);
        writer.Write("ApiMockHandlers, options: ");
        writer.Write(modulePrefix);
        writer.Write("ApiMockInstallOptions): Promise<");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiMock> {");
        writer.PushIndent();
        writer.Write("const state: ");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiMockState = { requests: [] };");
        writer.Write("await page.route(options.urlPattern, async (route) => handle");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiRoute(route, handlers, state, options));");
        writer.WriteLine("return {");
        writer.PushIndent();
        writer.WriteLine("state,");
        writer.WriteLine("requests: state.requests,");
        writer.WriteLine("requestsFor(endpointKey) {");
        writer.PushIndent();
        writer.Write("return state.requests.filter((request): request is ");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiMockRequestRecord<typeof endpointKey> => request.endpointKey === endpointKey);");
        writer.PopIndent();
        writer.WriteLine("},");
        writer.WriteLine("requestCountFor(endpointKey) {");
        writer.PushIndent();
        writer.WriteLine("return state.requests.filter((request) => request.endpointKey === endpointKey).length;");
        writer.PopIndent();
        writer.WriteLine("},");
        writer.WriteLine("firstRequestFor(endpointKey) {");
        writer.PushIndent();
        writer.Write("return state.requests.find((request): request is ");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiMockRequestRecord<typeof endpointKey> => request.endpointKey === endpointKey);");
        writer.PopIndent();
        writer.WriteLine("},");
        writer.WriteLine("lastRequestFor(endpointKey) {");
        writer.PushIndent();
        writer.WriteLine("for (let index = state.requests.length - 1; index >= 0; index -= 1) {");
        writer.PushIndent();
        writer.WriteLine("const request = state.requests[index];");
        writer.WriteLine("if (request.endpointKey === endpointKey) {");
        writer.PushIndent();
        writer.Write("return request as ");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiMockRequestRecord<typeof endpointKey>;");
        writer.PopIndent();
        writer.WriteLine("}");
        writer.PopIndent();
        writer.WriteLine("}");
        writer.WriteLine("return undefined;");
        writer.PopIndent();
        writer.WriteLine("},");
        writer.WriteLine("clearRequests(endpointKey) {");
        writer.PushIndent();
        writer.WriteLine("if (endpointKey === undefined) {");
        writer.PushIndent();
        writer.WriteLine("state.requests.length = 0;");
        writer.WriteLine("return;");
        writer.PopIndent();
        writer.WriteLine("}");
        writer.WriteLine("for (let index = state.requests.length - 1; index >= 0; index -= 1) {");
        writer.PushIndent();
        writer.WriteLine("if (state.requests[index].endpointKey === endpointKey) {");
        writer.PushIndent();
        writer.WriteLine("state.requests.splice(index, 1);");
        writer.PopIndent();
        writer.WriteLine("}");
        writer.PopIndent();
        writer.WriteLine("}");
        writer.PopIndent();
        writer.WriteLine("},");
        writer.PopIndent();
        writer.WriteLine("};");
        writer.PopIndent();
        writer.WriteLine("}");
        writer.WriteLine();
    }

    static void WriteRouteHandler(ref PooledCodeWriter writer, string modulePrefix)
    {
        var camelPrefix = ToCamelCase(modulePrefix);
        writer.Write("async function handle");
        writer.Write(modulePrefix);
        writer.Write("ApiRoute(route: Route, handlers: ");
        writer.Write(modulePrefix);
        writer.Write("ApiMockHandlers, state: ");
        writer.Write(modulePrefix);
        writer.Write("ApiMockState, options: ");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiMockInstallOptions) {");
        writer.PushIndent();
        writer.WriteLine("const request = route.request();");
        writer.WriteLine("const method = request.method().toUpperCase();");
        writer.WriteLine("const url = new URL(request.url());");
        writer.WriteLine("if (method === 'OPTIONS') {");
        writer.PushIndent();
        writer.WriteLine("await fulfillApiMockResponse(route, noContent(204));");
        writer.WriteLine("return;");
        writer.PopIndent();
        writer.WriteLine("}");
        writer.WriteLine();

        writer.Write("const match = match");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiEndpoint(method, url.pathname);");
        writer.WriteLine("if (!match) {");
        writer.PushIndent();
        writer.WriteLine("await fulfillUnhandledApiMockRequest(route, options, `Unhandled API mock request: ${method} ${url.pathname}`);");
        writer.WriteLine("return;");
        writer.PopIndent();
        writer.WriteLine("}");
        writer.WriteLine();

        writer.WriteLine("const body = await readApiMockRequestBody(request);");
        writer.Write("const query = decode");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiQuery(match.endpointKey, url.searchParams);");
        writer.Write("const record = {");
        writer.WriteLine();
        writer.PushIndent();
        writer.WriteLine("endpointKey: match.endpointKey,");
        writer.Write("endpointId: ");
        writer.Write(camelPrefix);
        writer.WriteLine("ApiEndpointIds[match.endpointKey],");
        writer.Write("operationId: ");
        writer.Write(camelPrefix);
        writer.WriteLine("ApiEndpointIds[match.endpointKey],");
        writer.Write("scopePolicies: ");
        writer.Write(camelPrefix);
        writer.WriteLine("ApiScopePolicies[match.endpointKey],");
        writer.WriteLine("method,");
        writer.WriteLine("pathname: url.pathname,");
