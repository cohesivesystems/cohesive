namespace Cohesive.Adapters.TypeScript;

/// <summary>
/// Emits a typed Playwright route mock host from a Cohesive API definition.
/// </summary>
public sealed class TypeScriptPlaywrightApiMockEmitter : IApiCodeEmitter
{
    readonly TypeScriptPlaywrightApiMockEmitterOptions options;

    /// <summary>
    /// Creates the emitter.
    /// </summary>
    public TypeScriptPlaywrightApiMockEmitter(TypeScriptPlaywrightApiMockEmitterOptions? options = null)
    {
        this.options = options ?? new TypeScriptPlaywrightApiMockEmitterOptions();
    }

    /// <inheritdoc />
    public string Language => "typescript-playwright";

    /// <inheritdoc />
    public CodeEmission Emit(in ApiCodeGenerationRequest request)
    {
        var models = BuildOperationModels(request.Definition);
        var modulePrefix = ToPascalCase(options.ModuleName);
        var writer = new PooledCodeWriter(
            initialCapacity: EstimateInitialCapacity(request.Definition),
            indentSize: options.IndentSize,
            newLine: options.NewLine);

        try
        {
            if (options.EmitAutoGeneratedHeader)
            {
                writer.WriteLine("/* <auto-generated/> */");
                writer.WriteLine();
            }

            WriteImports(ref writer, models);
            WriteEndpointTypes(ref writer, modulePrefix, models);
            WriteMockTypes(ref writer, modulePrefix, models);
            WriteResultBuilders(ref writer, modulePrefix, models);
            WriteInstallFunction(ref writer, modulePrefix);
            WriteRouteHandler(ref writer, modulePrefix);
            WriteMatcher(ref writer, modulePrefix, models);
            WriteDecoders(ref writer, modulePrefix, models);
            WriteRuntimeHelpers(ref writer, modulePrefix, models);

            return new CodeEmission(
                language: Language,
                documents: [new GeneratedCodeDocument(options.FileName, writer.ToString())]);
        }
        finally
        {
            writer.Dispose();
        }
    }

    /// <summary>
    /// Emits a definition directly.
    /// </summary>
    public CodeEmission Emit(ApiDefinition definition) => Emit(new ApiCodeGenerationRequest(definition));

    void WriteImports(ref PooledCodeWriter writer, IReadOnlyList<OperationModel> models)
    {
        writer.WriteLine("import type { Page, Request, Route } from '@playwright/test';");

        var imports = CollectTypeImports(models);
        if (imports.Length > 0)
        {
            writer.Write("import type { ");
            for (var i = 0; i < imports.Length; i++)
            {
                if (i > 0)
                    writer.Write(", ");

                writer.Write(imports[i]);
            }

            writer.Write(" } from ");
            writer.Write(Quote(options.ShapesImportPath));
            writer.WriteLine(";");
        }

        writer.WriteLine();
    }

    static void WriteEndpointTypes(ref PooledCodeWriter writer, string modulePrefix, IReadOnlyList<OperationModel> models)
    {
        var camelPrefix = ToCamelCase(modulePrefix);
        writer.Write("export type ");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiEndpointKey =");
        writer.PushIndent();
        if (models.Count == 0)
        {
            writer.WriteLine("never;");
        }
        else
        {
            for (var i = 0; i < models.Count; i++)
            {
                writer.Write("| ");
                writer.Write(Quote(models[i].Key));
                writer.WriteLine(i == models.Count - 1 ? ";" : string.Empty);
            }
        }
        writer.PopIndent();
        writer.WriteLine();

        writer.Write("export const ");
        writer.Write(camelPrefix);
        writer.WriteLine("ApiEndpointIds = {");
        writer.PushIndent();
        for (var i = 0; i < models.Count; i++)
        {
            writer.Write(models[i].Key);
            writer.Write(": ");
            writer.Write(Quote(models[i].Operation.Id.Value));
            writer.WriteLine(",");
        }
        writer.PopIndent();
        writer.Write("} as const satisfies Record<");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiEndpointKey, string>;");
        writer.WriteLine();

        WriteScopeMetadata(ref writer, modulePrefix, models);
        WriteEndpointMapInterface(ref writer, modulePrefix, models, "Route", static model => model.RouteType);
        WriteEndpointMapInterface(ref writer, modulePrefix, models, "Query", static model => model.QueryType);
        WriteEndpointMapInterface(ref writer, modulePrefix, models, "Body", static model => model.BodyType);
        WriteEndpointMapInterface(ref writer, modulePrefix, models, "ResponseBody", static model => model.ResponseBodyType);
        WriteResultMetadata(ref writer, modulePrefix, models);
        WriteResultBuilderInterface(ref writer, modulePrefix, models);
    }

    static void WriteScopeMetadata(ref PooledCodeWriter writer, string modulePrefix, IReadOnlyList<OperationModel> models)
    {
        var camelPrefix = ToCamelCase(modulePrefix);
        writer.Write("export interface ");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiScopePolicyMetadata {");
        writer.PushIndent();
        writer.WriteLine("readonly kind: string;");
        writer.WriteLine("readonly cardinality: 'single' | 'multiple';");
        writer.WriteLine("readonly binding: 'ambient' | 'header' | 'query' | 'route' | 'body' | 'resource';");
        writer.WriteLine("readonly access: 'requireSelected' | 'filterToAccessible' | 'validateAccessible';");
        writer.WriteLine("readonly singleScopeParameterName?: string;");
        writer.WriteLine("readonly multipleScopesParameterName?: string;");
        writer.WriteLine("readonly scopeModeParameterName?: string;");
        writer.WriteLine("readonly resourceParameterName?: string;");
        writer.WriteLine("readonly resourceDerivation?: { readonly strategy: string; readonly format?: string; readonly scopeField?: string; };");
        writer.WriteLine("readonly allowDefaultScope: boolean;");
        writer.PopIndent();
        writer.WriteLine("}");
        writer.WriteLine();

        writer.Write("export interface ");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiScopePolicyByEndpoint {");
        writer.PushIndent();
        for (var i = 0; i < models.Count; i++)
        {
            writer.Write("readonly ");
            writer.Write(models[i].Key);
            writer.Write(": readonly ");
            writer.Write(modulePrefix);
            writer.WriteLine("ApiScopePolicyMetadata[];");
        }
        writer.PopIndent();
        writer.WriteLine("}");
        writer.WriteLine();

        writer.Write("export const ");
        writer.Write(camelPrefix);
        writer.WriteLine("ApiScopePolicies = {");
        writer.PushIndent();
        for (var i = 0; i < models.Count; i++)
        {
            var model = models[i];
            writer.Write(model.Key);
            writer.WriteLine(": [");
            writer.PushIndent();
            for (var policyIndex = 0; policyIndex < model.Operation.ScopePolicies.Count; policyIndex++)
                WriteScopePolicy(ref writer, model.Operation.ScopePolicies[policyIndex]);
            writer.PopIndent();
            writer.WriteLine("],");
        }
        writer.PopIndent();
        writer.Write("} as const satisfies ");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiScopePolicyByEndpoint;");
        writer.WriteLine();
    }

    static void WriteScopePolicy(ref PooledCodeWriter writer, ApiScopePolicy policy)
    {
        writer.Write("{ kind: ");
        writer.Write(Quote(policy.ScopeKind));
        writer.Write(", cardinality: ");
        writer.Write(Quote(ToCamelCase(policy.Cardinality.ToString())));
        writer.Write(", binding: ");
        writer.Write(Quote(ToCamelCase(policy.Binding.ToString())));
        writer.Write(", access: ");
        writer.Write(Quote(ToCamelCase(policy.Access.ToString())));
        WriteOptionalScopePolicyProperty(ref writer, "singleScopeParameterName", policy.SingleScopeParameterName);
        WriteOptionalScopePolicyProperty(ref writer, "multipleScopesParameterName", policy.MultipleScopesParameterName);
        WriteOptionalScopePolicyProperty(ref writer, "scopeModeParameterName", policy.ScopeModeParameterName);
        WriteOptionalScopePolicyProperty(ref writer, "resourceParameterName", policy.ResourceParameterName);
        WriteResourceScopeDerivationProperty(ref writer, policy.ResourceDerivation);
        writer.Write(", allowDefaultScope: ");
        writer.Write(policy.AllowDefaultScope ? "true" : "false");
        writer.WriteLine(" },");
    }

    static void WriteResourceScopeDerivationProperty(ref PooledCodeWriter writer, ApiResourceScopeDerivation? derivation)
    {
        if (derivation is null)
            return;

        writer.Write(", resourceDerivation: { strategy: ");
        writer.Write(Quote(derivation.Strategy));
        WriteOptionalObjectProperty(ref writer, "format", derivation.Format);
        WriteOptionalObjectProperty(ref writer, "scopeField", derivation.ScopeField);
        writer.Write(" }");
    }

    static void WriteOptionalObjectProperty(ref PooledCodeWriter writer, string name, string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return;

        writer.Write(", ");
        writer.Write(name);
        writer.Write(": ");
        writer.Write(Quote(value));
    }

    static void WriteOptionalScopePolicyProperty(ref PooledCodeWriter writer, string name, string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
            return;

        writer.Write(", ");
        writer.Write(name);
        writer.Write(": ");
        writer.Write(Quote(value));
    }

    static void WriteEndpointMapInterface(
        ref PooledCodeWriter writer,
        string modulePrefix,
        IReadOnlyList<OperationModel> models,
        string name,
        Func<OperationModel, string> typeSelector)
    {
        writer.Write("export interface ");
        writer.Write(modulePrefix);
        writer.Write("Api");
        writer.Write(name);
        writer.WriteLine("ByEndpoint {");
        writer.PushIndent();
        for (var i = 0; i < models.Count; i++)
        {
            writer.Write("readonly ");
            writer.Write(models[i].Key);
            writer.Write(": ");
            writer.Write(typeSelector(models[i]));
            writer.WriteLine(";");
        }
        writer.PopIndent();
        writer.WriteLine("}");
        writer.WriteLine();
    }

    static void WriteResultMetadata(ref PooledCodeWriter writer, string modulePrefix, IReadOnlyList<OperationModel> models)
    {
        var camelPrefix = ToCamelCase(modulePrefix);
        writer.Write("export const ");
        writer.Write(camelPrefix);
        writer.WriteLine("ApiResults = {");
        writer.PushIndent();
        for (var i = 0; i < models.Count; i++)
        {
            writer.Write(models[i].Key);
            writer.WriteLine(": {");
            writer.PushIndent();
            for (var resultIndex = 0; resultIndex < models[i].Results.Length; resultIndex++)
            {
                var result = models[i].Results[resultIndex];
                writer.Write(result.MethodName);
                writer.Write(": { id: ");
                writer.Write(Quote(result.Id));
                writer.Write(", kind: ");
                writer.Write(Quote(result.Kind));
                writer.Write(", status: ");
                writer.Write(result.StatusCode.ToString(System.Globalization.CultureInfo.InvariantCulture));
                if (!string.IsNullOrWhiteSpace(result.ContentType))
                {
                    writer.Write(", contentType: ");
                    writer.Write(Quote(result.ContentType!));
                }

                writer.WriteLine(" },");
            }
            writer.PopIndent();
            writer.WriteLine("},");
        }
        writer.PopIndent();
        writer.WriteLine("} as const;");
        writer.WriteLine();
    }

    static void WriteResultBuilderInterface(ref PooledCodeWriter writer, string modulePrefix, IReadOnlyList<OperationModel> models)
    {
        writer.Write("export interface ");
        writer.Write(modulePrefix);
        writer.WriteLine("ApiResultBuilderByEndpoint {");
        writer.PushIndent();
        for (var i = 0; i < models.Count; i++)
        {
            writer.Write("readonly ");
            writer.Write(models[i].Key);
            writer.WriteLine(": {");
            writer.PushIndent();
            for (var resultIndex = 0; resultIndex < models[i].Results.Length; resultIndex++)
            {
                var result = models[i].Results[resultIndex];
                writer.Write("readonly ");
                writer.Write(result.MethodName);
                writer.Write(": ");
                if (result.IsVoid)
                    writer.Write("() => ApiMockResponse<void>;");
                else
                {
                    writer.Write("(body: ");
                    writer.Write(result.BodyTypeText);
                    writer.Write(") => ApiMockResponse<");
                    writer.Write(result.BodyTypeText);
                    writer.Write(">;");
                }

                writer.WriteLine();
            }
            writer.PopIndent();
            writer.WriteLine("};");
        }
        writer.PopIndent();
        writer.WriteLine("}");
        writer.WriteLine();
    }

