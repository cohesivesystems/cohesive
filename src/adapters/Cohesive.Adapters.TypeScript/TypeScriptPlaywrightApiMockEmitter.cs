    static ImmutableArray<OperationModel> BuildOperationModels(ApiDefinition definition)
    {
        var usedKeys = new HashSet<string>(StringComparer.Ordinal);
        var models = ImmutableArray.CreateBuilder<OperationModel>(definition.Operations.Count);
        for (var i = 0; i < definition.Operations.Count; i++)
        {
            var operation = definition.Operations[i];
            if (operation.Http is not { } http)
                continue;

            models.Add(new OperationModel(
                Operation: operation,
                Http: http,
                Key: CreateUniqueOperationKey(operation, usedKeys),
                RouteType: BuildRouteType(http),
                QueryType: BuildQueryType(http),
                BodyType: http.Body is { } body ? GetTypeScriptTypeText(body.BodyType) : "null",
                ResponseBodyType: BuildResponseBodyType(operation),
                Results: BuildResultModels(operation),
                QueryProperties: BuildQueryProperties(http),
                RouteParameterCount: CountRouteParameters(http.Route),
                RouteSegmentCount: CountRouteSegments(http.Route)));
        }

        return models.ToImmutable();
    }

    static string CreateUniqueOperationKey(ApiOperation operation, HashSet<string> usedKeys)
    {
        var baseKey = CreateOperationKey(operation);
        var key = baseKey;
        var suffix = 2;
        while (!usedKeys.Add(key))
        {
            key = $"{baseKey}{suffix}";
            suffix++;
        }

        return key;
    }

    static string CreateOperationKey(ApiOperation operation)
    {
        if (operation.Entity is not { } entity)
            return ToCamelCase(SanitizeIdentifier(operation.Name, pascalCase: true));

        var entityName = StripEntitySuffix(entity.Value);
        var operationName = operation.Name;
        if (string.Equals(operationName, "Query", StringComparison.OrdinalIgnoreCase))
            return $"query{Pluralize(entityName)}";
        if (string.Equals(operationName, "Get", StringComparison.OrdinalIgnoreCase)
            || string.Equals(operationName, "Create", StringComparison.OrdinalIgnoreCase)
            || string.Equals(operationName, "Revise", StringComparison.OrdinalIgnoreCase)
            || string.Equals(operationName, "Archive", StringComparison.OrdinalIgnoreCase)
            || string.Equals(operationName, "Validate", StringComparison.OrdinalIgnoreCase))
        {
            return $"{ToCamelCase(operationName)}{entityName}";
        }

        if (operationName.StartsWith("Validate", StringComparison.Ordinal))
            return $"{ToCamelCase(operationName)}{entityName}";

        if (operationName.Contains(entityName, StringComparison.OrdinalIgnoreCase))
            return ToCamelCase(SanitizeIdentifier(operationName, pascalCase: true));

        return $"{ToCamelCase(operationName)}{entityName}";
    }

    static string BuildRouteType(HttpBinding http)
    {
        var routeParameters = http.Parameters.Where(static parameter => parameter.Source == HttpParameterSource.Route).ToArray();
        if (routeParameters.Length == 0)
            return "Record<string, never>";

        var builder = new StringBuilder("{ ");
        for (var i = 0; i < routeParameters.Length; i++)
        {
            if (i > 0)
                builder.Append(' ');

            builder.Append("readonly ");
            builder.Append(ToCamelCase(routeParameters[i].Name));
            builder.Append(": ");
            builder.Append(GetTypeScriptTypeText(routeParameters[i].Type));
            builder.Append(';');
        }

        builder.Append(" }");
        return builder.ToString();
    }

    static string BuildQueryType(HttpBinding http)
    {
        if (http.Query is { } query)
            return GetTypeScriptTypeText(query.QueryType);

        var queryParameters = http.Parameters.Where(static parameter => parameter.Source == HttpParameterSource.Query).ToArray();
        if (queryParameters.Length == 0)
            return "Record<string, never>";

        var builder = new StringBuilder("{ ");
        for (var i = 0; i < queryParameters.Length; i++)
        {
            if (i > 0)
                builder.Append(' ');

            var parameter = queryParameters[i];
            builder.Append("readonly ");
            builder.Append(ToCamelCase(parameter.Name));
            if (parameter.IsOptional || CanSkipWhenUndefined(parameter.Type))
                builder.Append('?');

            builder.Append(": ");
            builder.Append(GetTypeScriptTypeText(parameter.Type));
            builder.Append(';');
        }

        builder.Append(" }");
        return builder.ToString();
    }

    static string BuildResponseBodyType(ApiOperation operation)
    {
        var types = operation.Results
            .Select(static result => GetTypeScriptTypeText(result.BodyType))
            .Distinct(StringComparer.Ordinal)
            .ToArray();

        return types.Length == 0 ? "void" : string.Join(" | ", types);
    }

    static ImmutableArray<ResultModel> BuildResultModels(ApiOperation operation)
    {
        var usedNames = new HashSet<string>(StringComparer.Ordinal);
        var results = ImmutableArray.CreateBuilder<ResultModel>(operation.Results.Count);
        for (var i = 0; i < operation.Results.Count; i++)
        {
            var result = operation.Results[i];
            results.Add(new ResultModel(
                Id: result.Id,
                Kind: ApiWireNames.ResultKind(result.Kind),
                MethodName: CreateUniqueResultMethodName(result.Id, usedNames),
                BodyTypeText: GetTypeScriptTypeText(result.BodyType),
                StatusCode: result.Http?.StatusCode ?? DefaultMockStatusCode(result.Kind, result.BodyType),
                ContentType: result.Http?.ContentType,
                IsVoid: result.BodyType == typeof(void)));
        }

        return results.ToImmutable();
    }

    static string CreateUniqueResultMethodName(string resultId, HashSet<string> usedNames)
    {
        var baseName = ToCamelCase(resultId);
        var name = baseName;
        var suffix = 2;
        while (!usedNames.Add(name))
        {
            name = $"{baseName}{suffix}";
            suffix++;
        }

