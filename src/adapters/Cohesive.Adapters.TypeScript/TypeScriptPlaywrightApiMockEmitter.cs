        writer.PushIndent();
        var methods = models.Select(static model => model.Http.Method).Distinct(StringComparer.Ordinal).OrderBy(static value => value, StringComparer.Ordinal).ToArray();
        for (var i = 0; i < methods.Length; i++)
        {
